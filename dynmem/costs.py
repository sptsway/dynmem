"""Write COSTS.md from the LLM call log. Prices come from configs/models.yaml only."""
from __future__ import annotations

import sqlite3
from pathlib import Path

import yaml


def build(cache_path="cache/llm.sqlite", models_yaml="configs/models.yaml") -> str:
    if not Path(cache_path).exists():
        return "# Costs\n\nNo LLM calls logged yet.\n"
    prices = {}
    if Path(models_yaml).exists():
        prices = (yaml.safe_load(Path(models_yaml).read_text()) or {}).get("prices", {}) or {}
    rows = sqlite3.connect(cache_path).execute(
        """SELECT provider, model, tag, SUM(cached=0), SUM(cached=1),
                  SUM(CASE WHEN cached=0 THEN input_tokens ELSE 0 END),
                  SUM(CASE WHEN cached=0 THEN output_tokens ELSE 0 END),
                  SUM(CASE WHEN cached=0 THEN latency_s ELSE 0 END)
           FROM call_log GROUP BY provider, model, tag ORDER BY provider, model, tag""").fetchall()
    lines = ["# Costs", "",
             "Generated by `python -m dynmem.costs` from `cache/llm.sqlite`. Cached calls cost nothing and are counted separately.",
             "Cost uses USD per million tokens from `configs/models.yaml` (`prices`). A dash means no price is set.", "",
             "| provider | model | tag | fresh calls | cached calls | input tokens | output tokens | API seconds | cost (USD) |",
             "|---|---|---|---|---|---|---|---|---|"]
    total, priced = 0.0, True
    for prov, model, tag, fresh, cached, tin, tout, secs in rows:
        p = prices.get(model)
        cost = None if not p else (tin * p["input_per_m"] + tout * p["output_per_m"]) / 1e6
        if cost is None:
            priced = False
        else:
            total += cost
        lines.append(f"| {prov} | {model} | {tag} | {fresh} | {cached} | {tin} | {tout} | {secs:.1f} | "
                     f"{'-' if cost is None else f'{cost:.4f}'} |")
    lines += ["", "Notes: `ollama` rows are local inference with no API cost. `gemini` rows are 18 probe calls on a free-tier key.",
              "Counts include dev tuning runs and one discarded partial test run, so they exceed the final result files.", ""]
    lines += [f"Total priced cost: {total:.4f} USD" + ("" if priced else " (excludes rows without a price)"), ""]
    return "\n".join(lines)


if __name__ == "__main__":
    Path("COSTS.md").write_text(build())
    print("wrote COSTS.md")
